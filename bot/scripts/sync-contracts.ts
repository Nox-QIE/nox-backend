/**
 * Copies ABI + bytecode of the Nox contracts from a local nox-contracts build (forge build) into
 * bot/src/chain/contracts.ts. Run after the contracts change:
 *   (cd ../nox-contracts && forge build) && node --import tsx bot/scripts/sync-contracts.ts
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const root = process.argv[2] ?? "../nox-contracts";
const commit = execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim();
const names = ["NoxGame", "NoxCredits"];
let out = `// Generated by bot/scripts/sync-contracts.ts from Nox-QIE/nox-contracts@${commit}. Do not edit.\n\n`;
for (const n of names) {
  const a = JSON.parse(readFileSync(`${root}/out/${n}.sol/${n}.json`, "utf8"));
  out += `export const ${n}Abi = ${JSON.stringify(a.abi)} as const;\n\n`;
  out += `export const ${n}Bytecode = "${a.bytecode.object}" as const;\n\n`;
}
writeFileSync("bot/src/chain/contracts.ts", out);
console.log(`synced ${names.join(", ")} from nox-contracts@${commit}`);
